-- WeStorage OMS - Esquema PostgreSQL (revision 2)
-- Alcance de esta revision:
--   * Rediseño de ordenes, despachos, bultos, tracking y estados.
--   * Normalizacion de couriers, servicios y cobertura geografica.
--   * Las demas entidades del esquema original se mantienen funcionalmente.
--
-- Este script crea el esquema sobre una base de datos ya existente.
-- No incluye DROP ni CREATE DATABASE para evitar operaciones destructivas.

BEGIN;

CREATE SCHEMA IF NOT EXISTS we;

-- -----------------------------------------------------------------------------
-- CLIENTES
-- -----------------------------------------------------------------------------

CREATE TABLE we.clients (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar NOT NULL,
    dni varchar NOT NULL,
    wms_code smallint NOT NULL,
    url_site varchar,
    active boolean NOT NULL DEFAULT true,
    email varchar NOT NULL,
    parent_id smallint,
    CONSTRAINT clients_dni_unique UNIQUE (dni)
);

CREATE TABLE we.stores (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar NOT NULL,
    name varchar NOT NULL,
    address varchar,
    active boolean NOT NULL DEFAULT true,
    CONSTRAINT stores_code_unique UNIQUE (code)
);

CREATE TABLE we.clients_stores (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id smallint NOT NULL,
    store_id smallint NOT NULL,
    principal boolean NOT NULL DEFAULT false,
    CONSTRAINT clients_stores_clients_fk
        FOREIGN KEY (client_id) REFERENCES we.clients(id) ON DELETE RESTRICT
);

-- -----------------------------------------------------------------------------
-- CATALOGOS GENERALES Y GEOGRAFIA
-- -----------------------------------------------------------------------------

CREATE TABLE we.common_types (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar NOT NULL,
    type_code varchar NOT NULL,
    active boolean NOT NULL DEFAULT true,
    value varchar NOT NULL
);

CREATE TABLE we.regions (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar NOT NULL,
    active boolean NOT NULL DEFAULT true
);

CREATE TABLE we.communes (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_id smallint NOT NULL,
    name varchar NOT NULL,
    aliases json,
    CONSTRAINT communes_regions_fk
        FOREIGN KEY (region_id) REFERENCES we.regions(id) ON DELETE RESTRICT
);

CREATE TABLE we.economic_activities (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar NOT NULL,
    name varchar NOT NULL,
    active boolean NOT NULL DEFAULT true
);

-- -----------------------------------------------------------------------------
-- COURIERS, SERVICIOS Y COBERTURA
-- -----------------------------------------------------------------------------

CREATE TABLE we.couriers (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar NOT NULL,
    code varchar NOT NULL,
    tracking_url_template varchar,
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT couriers_code_unique UNIQUE (code)
);

CREATE TABLE we.courier_services (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    courier_id smallint NOT NULL,
    code varchar NOT NULL,
    name varchar NOT NULL,
    description varchar,
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT courier_services_courier_fk
        FOREIGN KEY (courier_id) REFERENCES we.couriers(id) ON DELETE RESTRICT,
    CONSTRAINT courier_services_code_unique UNIQUE (courier_id, code)
);

-- Traduce la comuna estandar del OMS al codigo y nombre utilizados por el courier.
CREATE TABLE we.courier_communes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    courier_id smallint NOT NULL,
    commune_id smallint NOT NULL,
    external_code varchar,
    external_name varchar NOT NULL,
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT courier_communes_courier_fk
        FOREIGN KEY (courier_id) REFERENCES we.couriers(id) ON DELETE RESTRICT,
    CONSTRAINT courier_communes_commune_fk
        FOREIGN KEY (commune_id) REFERENCES we.communes(id) ON DELETE RESTRICT,
    CONSTRAINT courier_communes_internal_unique UNIQUE (courier_id, commune_id)
);

CREATE UNIQUE INDEX courier_communes_external_code_unique
    ON we.courier_communes (courier_id, external_code)
    WHERE external_code IS NOT NULL;

-- Indica que servicio cubre una comuna. JSONB queda reservado para restricciones
-- particulares del proveedor que no ameriten columnas propias.
CREATE TABLE we.courier_service_coverage (
    courier_service_id smallint NOT NULL,
    courier_commune_id integer NOT NULL,
    active boolean NOT NULL DEFAULT true,
    priority smallint NOT NULL DEFAULT 100,
    restrictions jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT courier_service_coverage_pk
        PRIMARY KEY (courier_service_id, courier_commune_id),
    CONSTRAINT courier_service_coverage_service_fk
        FOREIGN KEY (courier_service_id)
        REFERENCES we.courier_services(id) ON DELETE RESTRICT,
    CONSTRAINT courier_service_coverage_commune_fk
        FOREIGN KEY (courier_commune_id)
        REFERENCES we.courier_communes(id) ON DELETE RESTRICT,
    CONSTRAINT courier_service_coverage_priority_check CHECK (priority >= 0)
);

-- -----------------------------------------------------------------------------
-- SEGURIDAD Y PERMISOS (SE CONSERVA EL MODELO ORIGINAL)
-- -----------------------------------------------------------------------------

CREATE TABLE we.roles (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar NOT NULL,
    active boolean NOT NULL DEFAULT true
);

CREATE TABLE we.system_modules (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar NOT NULL,
    active boolean NOT NULL DEFAULT true,
    actions json
);

CREATE TABLE we.roles_modules (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rol_id smallint NOT NULL,
    module_id smallint NOT NULL,
    actions_active json,
    active boolean NOT NULL DEFAULT true,
    CONSTRAINT roles_modules_roles_fk
        FOREIGN KEY (rol_id) REFERENCES we.roles(id) ON DELETE RESTRICT,
    CONSTRAINT roles_modules_system_modules_fk
        FOREIGN KEY (module_id) REFERENCES we.system_modules(id) ON DELETE RESTRICT
);

CREATE TABLE we.users (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id smallint NOT NULL,
    name varchar NOT NULL,
    dni varchar NOT NULL,
    email varchar NOT NULL,
    phone varchar,
    username varchar NOT NULL,
    password varchar NOT NULL,
    salt varchar NOT NULL,
    rol_id smallint NOT NULL,
    CONSTRAINT users_dni_unique UNIQUE (dni),
    CONSTRAINT users_clients_fk
        FOREIGN KEY (client_id) REFERENCES we.clients(id) ON DELETE RESTRICT,
    CONSTRAINT users_roles_fk
        FOREIGN KEY (rol_id) REFERENCES we.roles(id) ON DELETE RESTRICT
);

-- -----------------------------------------------------------------------------
-- PRODUCTOS Y KITS (SE CONSERVA EL MODELO ORIGINAL)
-- -----------------------------------------------------------------------------

CREATE TABLE we.products (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id smallint NOT NULL,
    code varchar NOT NULL,
    title varchar NOT NULL,
    ean13_code varchar,
    active boolean NOT NULL DEFAULT true,
    type smallint NOT NULL DEFAULT 1,
    CONSTRAINT products_clients_fk
        FOREIGN KEY (client_id) REFERENCES we.clients(id)
);

CREATE TABLE we.products_kits (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id_kit integer NOT NULL,
    product_id_recipe integer NOT NULL,
    quantity smallint NOT NULL DEFAULT 1,
    CONSTRAINT products_kits_product_kit_fk
        FOREIGN KEY (product_id_kit) REFERENCES we.products(id) ON DELETE RESTRICT,
    CONSTRAINT products_kits_product_recipe_fk
        FOREIGN KEY (product_id_recipe) REFERENCES we.products(id) ON DELETE RESTRICT
);

-- -----------------------------------------------------------------------------
-- ESTADOS INTERNOS DEL OMS
-- -----------------------------------------------------------------------------

-- Macroestados visibles para los clientes.
CREATE TABLE we.order_statuses (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(50) NOT NULL UNIQUE,
    name varchar(100) NOT NULL,
    description varchar(500),
    is_final boolean NOT NULL DEFAULT false,
    active boolean NOT NULL DEFAULT true,
    display_order smallint NOT NULL DEFAULT 0
);

-- Estados operativos detallados informados por el WMS.
CREATE TABLE we.warehouse_statuses (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(50) NOT NULL UNIQUE,
    name varchar(100) NOT NULL,
    description varchar(500),
    is_final boolean NOT NULL DEFAULT false,
    active boolean NOT NULL DEFAULT true,
    display_order smallint NOT NULL DEFAULT 0
);

CREATE TABLE we.shipment_statuses (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(50) NOT NULL UNIQUE,
    name varchar(100) NOT NULL,
    description varchar(500),
    is_final boolean NOT NULL DEFAULT false,
    active boolean NOT NULL DEFAULT true,
    display_order smallint NOT NULL DEFAULT 0
);

CREATE TABLE we.shipment_package_statuses (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(50) NOT NULL UNIQUE,
    name varchar(100) NOT NULL,
    description varchar(500),
    is_final boolean NOT NULL DEFAULT false,
    active boolean NOT NULL DEFAULT true,
    display_order smallint NOT NULL DEFAULT 0
);

