-- -----------------------------------------------------------------------------
-- ORDENES
-- -----------------------------------------------------------------------------

CREATE TABLE we.orders (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_type smallint NOT NULL,
    client_id smallint NOT NULL,
    client_site varchar,
    client_order_number varchar NOT NULL,
    order_date date NOT NULL,
    order_value real NOT NULL,
    dispatch_type smallint NOT NULL,

    -- Destinatario y unica direccion de entrega de la orden.
    recipient_name varchar NOT NULL,
    recipient_dni varchar,
    shipping_address varchar NOT NULL,
    recipient_phone varchar,
    recipient_email varchar,
    shipping_comments varchar,
    commune_id smallint NOT NULL,

    -- Estado general visible y estado operativo del WMS.
    status_id smallint NOT NULL,
    warehouse_status_id smallint NOT NULL,

    warehouse_id smallint NOT NULL,
    wms_ds_id integer,
    wms_ds_date date,
    channel_sale varchar,
    channel_id smallint,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT orders_client_fk
        FOREIGN KEY (client_id) REFERENCES we.clients(id) ON DELETE RESTRICT,
    CONSTRAINT orders_commune_fk
        FOREIGN KEY (commune_id) REFERENCES we.communes(id) ON DELETE RESTRICT,
    CONSTRAINT orders_status_fk
        FOREIGN KEY (status_id) REFERENCES we.order_statuses(id) ON DELETE RESTRICT,
    CONSTRAINT orders_warehouse_status_fk
        FOREIGN KEY (warehouse_status_id)
        REFERENCES we.warehouse_statuses(id) ON DELETE RESTRICT
);

CREATE INDEX orders_client_order_number_idx
    ON we.orders (client_id, client_order_number);
CREATE INDEX orders_client_status_date_idx
    ON we.orders (client_id, status_id, order_date);
CREATE INDEX orders_warehouse_status_idx
    ON we.orders (warehouse_status_id);

CREATE TABLE we.order_items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id integer NOT NULL,
    product_id integer NOT NULL,
    quantity_requested integer NOT NULL DEFAULT 0,
    quantity_prepared integer NOT NULL DEFAULT 0,
    CONSTRAINT order_items_order_fk
        FOREIGN KEY (order_id) REFERENCES we.orders(id) ON DELETE RESTRICT,
    CONSTRAINT order_items_product_fk
        FOREIGN KEY (product_id) REFERENCES we.products(id) ON DELETE RESTRICT,
    CONSTRAINT order_items_quantity_requested_check CHECK (quantity_requested > 0),
    CONSTRAINT order_items_quantity_prepared_check CHECK (quantity_prepared >= 0)
);

CREATE INDEX order_items_order_idx ON we.order_items (order_id);

-- Se conserva para metadata adicional mientras se define su uso definitivo.
CREATE TABLE we.orders_items_info (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id integer NOT NULL,
    product_id integer NOT NULL,
    info json NOT NULL,
    CONSTRAINT orders_items_info_order_fk
        FOREIGN KEY (order_id) REFERENCES we.orders(id) ON DELETE RESTRICT,
    CONSTRAINT orders_items_info_product_fk
        FOREIGN KEY (product_id) REFERENCES we.products(id) ON DELETE RESTRICT
);

CREATE TABLE we.orders_documents (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id integer NOT NULL,
    type_id smallint NOT NULL,
    link varchar NOT NULL,
    CONSTRAINT orders_documents_order_fk
        FOREIGN KEY (order_id) REFERENCES we.orders(id) ON DELETE RESTRICT,
    CONSTRAINT orders_documents_common_types_fk
        FOREIGN KEY (type_id) REFERENCES we.common_types(id) ON DELETE RESTRICT
);

-- Historial del macroestado. Los detalles de sin stock, daño o merma pueden
-- registrarse en reason/comments y en metadata (por ejemplo SKU y cantidad).
CREATE TABLE we.order_status_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id integer NOT NULL,
    previous_status_id smallint,
    new_status_id smallint NOT NULL,
    source varchar(30) NOT NULL,
    changed_by_user_id smallint,
    reason varchar,
    comments text,
    external_reference varchar,
    metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT order_status_history_order_fk
        FOREIGN KEY (order_id) REFERENCES we.orders(id) ON DELETE RESTRICT,
    CONSTRAINT order_status_history_previous_status_fk
        FOREIGN KEY (previous_status_id)
        REFERENCES we.order_statuses(id) ON DELETE RESTRICT,
    CONSTRAINT order_status_history_new_status_fk
        FOREIGN KEY (new_status_id)
        REFERENCES we.order_statuses(id) ON DELETE RESTRICT,
    CONSTRAINT order_status_history_user_fk
        FOREIGN KEY (changed_by_user_id) REFERENCES we.users(id) ON DELETE RESTRICT,
    CONSTRAINT order_status_history_source_check
        CHECK (source IN ('USER', 'SYSTEM', 'WMS', 'SALES_CHANNEL', 'COURIER'))
);

CREATE INDEX order_status_history_order_date_idx
    ON we.order_status_history (order_id, created_at DESC);

-- -----------------------------------------------------------------------------
-- DESPACHOS, BULTOS Y TRACKING
-- -----------------------------------------------------------------------------

-- Una orden puede no tener despachos, o tener varios intentos de despacho.
CREATE TABLE we.shipments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id integer NOT NULL,
    courier_service_id smallint NOT NULL,
    status_id smallint NOT NULL,
    external_dispatch_id varchar(100),
    shipping_cost numeric(14,2),
    requested_at timestamptz,
    confirmed_at timestamptz,
    dispatched_at timestamptz,
    delivered_at timestamptz,
    cancelled_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT shipments_order_fk
        FOREIGN KEY (order_id) REFERENCES we.orders(id) ON DELETE RESTRICT,
    CONSTRAINT shipments_courier_service_fk
        FOREIGN KEY (courier_service_id)
        REFERENCES we.courier_services(id) ON DELETE RESTRICT,
    CONSTRAINT shipments_status_fk
        FOREIGN KEY (status_id) REFERENCES we.shipment_statuses(id) ON DELETE RESTRICT,
    CONSTRAINT shipments_shipping_cost_check
        CHECK (shipping_cost IS NULL OR shipping_cost >= 0)
);

CREATE INDEX shipments_order_idx ON we.shipments (order_id);
CREATE INDEX shipments_status_idx ON we.shipments (status_id);
CREATE INDEX shipments_external_dispatch_idx
    ON we.shipments (courier_service_id, external_dispatch_id)
    WHERE external_dispatch_id IS NOT NULL;

-- El WMS informa la cantidad final de bultos. Se crea una fila por bulto; no se
-- registran por ahora peso, volumen, dimensiones ni productos contenidos.
CREATE TABLE we.shipment_packages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id bigint NOT NULL,
    package_number integer NOT NULL,
    external_package_id varchar(100),
    tracking_number varchar(150),
    label_url varchar(500),
    label_format varchar(20),
    status_id smallint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT shipment_packages_shipment_fk
        FOREIGN KEY (shipment_id) REFERENCES we.shipments(id) ON DELETE RESTRICT,
    CONSTRAINT shipment_packages_status_fk
        FOREIGN KEY (status_id)
        REFERENCES we.shipment_package_statuses(id) ON DELETE RESTRICT,
    CONSTRAINT shipment_packages_number_unique
        UNIQUE (shipment_id, package_number),
    CONSTRAINT shipment_packages_number_check CHECK (package_number > 0)
);

CREATE INDEX shipment_packages_tracking_idx
    ON we.shipment_packages (tracking_number)
    WHERE tracking_number IS NOT NULL;

-- Historial original notificado por el courier para cada tracking/bulto.
CREATE TABLE we.shipment_tracking_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_package_id bigint NOT NULL,
    external_status_code varchar(100) NOT NULL,
    external_status_name varchar(200),
    normalized_status_id smallint,
    description text,
    location varchar(250),
    event_at timestamptz NOT NULL,
    received_at timestamptz NOT NULL DEFAULT now(),
    external_event_id varchar(150),
    raw_payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT shipment_tracking_events_package_fk
        FOREIGN KEY (shipment_package_id)
        REFERENCES we.shipment_packages(id) ON DELETE RESTRICT,
    CONSTRAINT shipment_tracking_events_status_fk
        FOREIGN KEY (normalized_status_id)
        REFERENCES we.shipment_package_statuses(id) ON DELETE RESTRICT
);

CREATE INDEX shipment_tracking_events_package_date_idx
    ON we.shipment_tracking_events (shipment_package_id, event_at DESC);

CREATE UNIQUE INDEX shipment_tracking_events_external_unique
    ON we.shipment_tracking_events (shipment_package_id, external_event_id)
    WHERE external_event_id IS NOT NULL;

-- -----------------------------------------------------------------------------
-- EQUIVALENCIAS DE ESTADOS EXTERNOS
-- source_code identifica temporalmente al WMS o canal. Cuando se diseñe la
-- tabla integrations, estas columnas se reemplazaran por integration_id.
-- -----------------------------------------------------------------------------

CREATE TABLE we.wms_status_mappings (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code varchar(50) NOT NULL,
    external_status_code varchar(100) NOT NULL,
    external_status_name varchar(200),
    warehouse_status_id smallint NOT NULL,
    order_status_id smallint,
    active boolean NOT NULL DEFAULT true,
    CONSTRAINT wms_status_mappings_warehouse_status_fk
        FOREIGN KEY (warehouse_status_id)
        REFERENCES we.warehouse_statuses(id) ON DELETE RESTRICT,
    CONSTRAINT wms_status_mappings_order_status_fk
        FOREIGN KEY (order_status_id)
        REFERENCES we.order_statuses(id) ON DELETE RESTRICT,
    CONSTRAINT wms_status_mappings_unique
        UNIQUE (source_code, external_status_code)
);

CREATE TABLE we.channel_status_mappings (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code varchar(50) NOT NULL,
    external_status_code varchar(100) NOT NULL,
    external_status_name varchar(200),
    order_status_id smallint NOT NULL,
    active boolean NOT NULL DEFAULT true,
    CONSTRAINT channel_status_mappings_order_status_fk
        FOREIGN KEY (order_status_id)
        REFERENCES we.order_statuses(id) ON DELETE RESTRICT,
    CONSTRAINT channel_status_mappings_unique
        UNIQUE (source_code, external_status_code)
);

CREATE TABLE we.courier_status_mappings (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    courier_id smallint NOT NULL,
    external_status_code varchar(100) NOT NULL,
    external_status_name varchar(200),
    shipment_package_status_id smallint NOT NULL,
    active boolean NOT NULL DEFAULT true,
    CONSTRAINT courier_status_mappings_courier_fk
        FOREIGN KEY (courier_id) REFERENCES we.couriers(id) ON DELETE RESTRICT,
    CONSTRAINT courier_status_mappings_package_status_fk
        FOREIGN KEY (shipment_package_status_id)
        REFERENCES we.shipment_package_statuses(id) ON DELETE RESTRICT,
    CONSTRAINT courier_status_mappings_unique
        UNIQUE (courier_id, external_status_code)
);

-- -----------------------------------------------------------------------------
-- LOGS Y AUDITORIA (SE CONSERVA EL MODELO ORIGINAL)
-- -----------------------------------------------------------------------------

CREATE TABLE we.orders_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action varchar NOT NULL,
    value json NOT NULL,
    user_id smallint NOT NULL,
    date timestamp without time zone NOT NULL DEFAULT now(),
    order_id integer NOT NULL,
    CONSTRAINT orders_logs_order_fk
        FOREIGN KEY (order_id) REFERENCES we.orders(id) ON DELETE RESTRICT,
    CONSTRAINT orders_logs_user_fk
        FOREIGN KEY (user_id) REFERENCES we.users(id) ON DELETE RESTRICT
);

CREATE TABLE we.action_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module varchar NOT NULL,
    action varchar NOT NULL,
    value json NOT NULL,
    reference_id integer NOT NULL,
    user_id smallint NOT NULL,
    date timestamp without time zone NOT NULL DEFAULT now(),
    CONSTRAINT action_logs_user_fk
        FOREIGN KEY (user_id) REFERENCES we.users(id) ON DELETE RESTRICT
);

COMMIT;
